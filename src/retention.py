import os
import json
from dotenv import load_dotenv

load_dotenv()
MODEL = "gemini-3.8-flash"


def _get_key():
    key = os.getenv("GEMINI_API_KEY")
    if key:
        return key
    try:
        import streamlit as st
        return st.secrets.get("GEMINI_API_KEY")
    except Exception:
        return None


def _template(name, contract, monthly):
    email = (f"Dear {name},\n\nThank you for being with us. We would like to "
            f"offer you a special loyalty benefit: switch to a longer plan "
            f"and enjoy a discount plus free Tech Support for 3 months.\n\n"
            f"Reply to this email or call our care team to claim it.\n\n"
            f"Warm regards,\nCustomer Care Team")
    sms = (f"Hi {name}, enjoy a special loyalty offer on your plan with free "
        f"Tech Support for 3 months. Call customer care to claim it.")
    return {"email": email, "sms": sms, "source": "Built-in template (Gemini unavailable)"}


def generate_offer(name, level, drivers, contract, monthly):
    """Ask Gemini for a personalised retention email and SMS."""
    key = _get_key()
    if not key:
        return _template(name, contract, monthly)

    reasons = ", ".join(drivers[drivers["Effect"] == "Increases risk"]["Factor"].head(3))
    prompt = f"""You are a customer retention specialist at a telecom company.
Write a short, friendly retention message for a customer.

Customer name: {name}
Current contract: {contract}
Monthly bill: {monthly}
Main reasons they may leave: {reasons}

Rules:
- Only offer things from this approved list: discount on a 1-year or 2-year plan,
free Tech Support for 3 months, bill credit for automatic payment, free plan review.
- Choose the offers that best match the reasons above.
- Do NOT mention churn, risk scores or AI predictions.
- Email: under 90 words, with greeting and sign-off "Customer Care Team".
- SMS: under 160 characters.
Return ONLY valid JSON with keys "email" and "sms"."""

    try:
        from google import genai
        client = genai.Client(api_key=key)
        resp = client.models.generate_content(model=MODEL, contents=prompt)
        text = resp.text.strip().replace("```json", "").replace("```", "").strip()
        data = json.loads(text)
        return {"email": data["email"], "sms": data["sms"],
                "source": f"Generated by Google Gemini ({MODEL})"}
    except Exception:
        return _template(name, contract, monthly)




def executive_summary(stats):
    """Short plain-text summary for the PDF report (Gemini, with fallback)."""
    fallback = (
        f"{stats['customers']} customers were analysed. {stats['high']} are high "
        f"risk and {stats['medium']} are medium risk. The expected monthly revenue "
        f"at risk is {stats['rev_risk']:.0f}. Customers on {stats['worst_contract']} "
        f"contracts show the highest average risk, so retention offers should "
        f"start with them.")
    key = _get_key()
    if not key:
        return fallback
    prompt = f"""You are a business analyst at a telecom company.
Write a short executive summary (maximum 110 words, plain text, no bullet
points, no markdown, no emojis) of this churn analysis:
- Customers analysed: {stats['customers']}
- High risk: {stats['high']}, Medium risk: {stats['medium']}, Low risk: {stats['low']}
- Average churn risk: {stats['avg_risk']:.1f}%
- Expected monthly revenue at risk: {stats['rev_risk']:.0f}
- Contract type with the highest average risk: {stats['worst_contract']}
End with two recommended actions for the retention team."""
    try:
        from google import genai
        client = genai.Client(api_key=key)
        resp = client.models.generate_content(model=MODEL, contents=prompt)
        return resp.text.strip()
    except Exception:
        return fallback